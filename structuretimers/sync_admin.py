class ScopedSyncAdmin(admin.ModelAdmin):
    """Default model permissions must never bypass the dedicated AA permission."""

    sync_permission = "structuretimers.manage_timer_sharing"

    def has_module_permission(self, request):
        return request.user.has_perm(self.sync_permission)

    def has_view_permission(self, request, obj=None):
        return self.has_module_permission(request)

    def has_add_permission(self, request):
        return self.has_module_permission(request)

    def has_change_permission(self, request, obj=None):
        return self.has_module_permission(request)

    def has_delete_permission(self, request, obj=None):
        return self.has_module_permission(request)


class ReceivingKeyForm(forms.ModelForm):
    rotate = forms.BooleanField(
        required=False,
        help_text="Generate a replacement key. The previous key stops working immediately.",
    )

    class Meta:
        model = TimerSyncKey
        fields = ("name", "source_instance", "enabled", "allow_opsec", "expires_at")


@admin.register(TimerSyncKey)
class ReceivingKeyAdmin(ScopedSyncAdmin):
    """Only the creation/rotation response contains plaintext; subsequent views do not."""

    sync_permission = "structuretimers.manage_sync_keys"
    form = ReceivingKeyForm
    fields = (
        "local_instance",
        "name",
        "source_instance",
        "enabled",
        "allow_opsec",
        "expires_at",
        "rotate",
        "id",
        "created_by",
        "created_at",
        "last_used_at",
    )
    readonly_fields = (
        "local_instance",
        "id",
        "created_by",
        "created_at",
        "last_used_at",
    )
    list_display = (
        "name",
        "source_instance",
        "enabled",
        "allow_opsec",
        "expires_at",
        "last_used_at",
    )
    actions = None

    @admin.display(description="This board's instance UUID")
    def local_instance(self, obj):
        return TimerSyncConfig.current().instance_id

    def save_model(self, request, obj, form, change):
        if not change:
            obj.created_by = request.user
        if (
            not change
            or form.cleaned_data.get("rotate")
            or "source_instance" in form.changed_data
        ):
            obj._issued_secret = obj.generate()
        super().save_model(request, obj, form, change)
        TimerSyncAudit.objects.create(
            source_instance=obj.source_instance,
            key=obj,
            actor=request.user,
            action="key_changed",
            result="rotated" if hasattr(obj, "_issued_secret") else "updated",
        )

    def _response(self, request, obj):
        response = TemplateResponse(
            request,
            "admin/structuretimers/sync_key_issued.html",
            {
                **self.admin_site.each_context(request),
                "title": "Timer sync key issued",
                "opts": self.model._meta,
                "secret": obj._issued_secret,
            },
        )
        response["Cache-Control"] = "private, no-store"
        response["Referrer-Policy"] = "no-referrer"
        return response

    def response_add(self, request, obj, post_url_continue=None):
        return self._response(request, obj)

    def response_change(self, request, obj):
        if hasattr(obj, "_issued_secret"):
            return self._response(request, obj)
        return super().response_change(request, obj)


class OutboundCredentialForm(forms.ModelForm):
    secret = forms.CharField(
        required=False,
        max_length=100,
        widget=forms.PasswordInput(render_value=False),
        help_text="Write-only. Leave blank to keep the saved key. Re-enter after changing the destination URL.",
    )

    class Meta:
        model = TimerSyncCredential
        fields = ("destination",)

    def clean(self):
        data = super().clean()
        if not self.instance.pk and not data.get("secret"):
            self.add_error("secret", "Enter the key generated by the receiving board.")
        if data.get("secret") and data.get("destination"):
            self.instance.destination = data["destination"]
            self.instance.set_secret(data["secret"])
        return data


@admin.register(TimerSyncCredential)
class OutboundCredentialAdmin(ScopedSyncAdmin):
    sync_permission = "structuretimers.manage_sync_keys"
    form = OutboundCredentialForm
    fields = ("destination", "endpoint", "secret", "updated_at")
    readonly_fields = ("endpoint", "updated_at")
    list_display = ("destination", "updated_at")
    actions = None

    @admin.display(description="Receiving endpoint")
    def endpoint(self, obj):
        return (
            obj.destination.endpoint
            if obj.destination_id
            else "Choose the destination and verify its endpoint before saving."
        )

    @method_decorator(sensitive_post_parameters("secret"))
    def changeform_view(self, request, object_id=None, form_url="", extra_context=None):
        return super().changeform_view(request, object_id, form_url, extra_context)

    def save_model(self, request, obj, form, change):
        # The password is encrypted during form validation, never a model field.
        super().save_model(request, obj, form, change)
        TimerSyncAudit.objects.create(
            action="credential_changed",
            result="updated",
            actor=request.user,
            destination=obj.destination,
        )


@admin.register(TimerSyncDestination)
class DestinationAdmin(ScopedSyncAdmin):
    fields = ("name", "endpoint", "scope", "enabled", "authorized_by", "updated_at")
    readonly_fields = ("authorized_by", "updated_at")
    list_display = ("name", "endpoint", "scope", "enabled", "authorized_by")
    actions = None

    def save_model(self, request, obj, form, change):
        if obj.scope == "all" and not request.user.has_perm(
            "structuretimers.opsec_access"
        ):
            raise PermissionDenied("Sharing OPSEC timers also requires OPSEC access.")
        obj.authorized_by = request.user
        obj.needs_backfill = True
        super().save_model(request, obj, form, change)
        TimerSyncAudit.objects.create(
            action="sharing_changed",
            result="enabled" if obj.enabled else "disabled",
            actor=request.user,
            destination=obj,
        )

    def save_related(self, request, form, formsets, change):
        super().save_related(request, form, formsets, change)
        transaction.on_commit(_kick)


@admin.register(TimerSyncConfig)
class ConfigAdmin(ScopedSyncAdmin):
    fields = ("instance_id", "replica", "master_source")
    readonly_fields = ("instance_id",)
    actions = None

    def has_add_permission(self, request):
        return (
            super().has_add_permission(request) and not TimerSyncConfig.objects.exists()
        )

    def has_delete_permission(self, request, obj=None):
        return False

    def save_model(self, request, obj, form, change):
        super().save_model(request, obj, form, change)
        TimerSyncAudit.objects.create(
            action="replica_mode",
            result="enabled" if obj.replica else "disabled",
            actor=request.user,
        )


class SyncReadOnlyAdmin(ScopedSyncAdmin):
    actions = None

    def has_add_permission(self, request):
        return False

    def has_change_permission(self, request, obj=None):
        return False

    def has_delete_permission(self, request, obj=None):
        return False


