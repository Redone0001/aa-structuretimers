@admin.register(TimerSyncAudit)
class AuditAdmin(SyncReadOnlyAdmin):
    fields = (
        "at",
        "actor",
        "source_instance",
        "timer_uuid",
        "action",
        "result",
        "key",
        "destination",
    )
    readonly_fields = fields
    list_display = ("at", "actor", "source_instance", "action", "result")
    list_filter = ("action", "result")

    def has_module_permission(self, request):
        return super().has_module_permission(request) or request.user.has_perm(
            "structuretimers.manage_sync_keys"
        )
